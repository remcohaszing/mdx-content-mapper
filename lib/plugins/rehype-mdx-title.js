import { isObject } from '../util/misc.js'
import { definePlugin } from '../util/plugin.js'

definePlugin('rehype-mdx-title', (options) => {
  const opts = isObject(options) ? options : {}
  const maxRank = Number(opts.maxRank || 1)
  const name = String(opts.name || 'title')
  let hasTitle = false

  return {
    visit(node) {
      hasTitle ||= node.type === 'heading' && node.depth <= maxRank
    },

    finalize() {
      return [
        `/** Generated by [rehype-mdx-title](https://github.com/remcohaszing/rehype-mdx-title) */\nexport const ${
          name
        } = /** @type {string${hasTitle ? '' : ' | undefined'}} */ ('')`,
        []
      ]
    }
  }
})
