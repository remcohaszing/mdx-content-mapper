/**
 * @import { Literal } from 'mdast'
 * @import { ParsedNode } from 'yaml'
 * @import { SpanMapping } from '../protocol.js'
 */

import { parse } from 'toml'
import { Composer, isAlias, isMap, isScalar, isSeq, LineCounter, Parser } from 'yaml'

import { isObject, nonNull } from '../util/misc.js'
import { definePlugin } from '../util/plugin.js'

/**
 * @param {ParsedNode} node
 * @param {string} js
 * @param {number} indent
 * @param {SpanMapping[]} mappings
 * @param {(name: string, code: string) => undefined} collect
 * @param {boolean} [isAnchor]
 * @returns {string}
 */
function visit(node, js, indent, mappings, collect, isAnchor) {
  if (!isAnchor && node.anchor) {
    collect(node.anchor, visit(node, '', 2, mappings, collect, true))
    return js + node.anchor
  }

  if (isMap(node)) {
    js += '{\n'
    for (let index = 0; index < node.items.length; index += 1) {
      const item = node.items[index]
      if (index !== 0) {
        js += ',\n'
      }
      js += ' '.repeat(indent * 2)
      js = visit(item.key, js, indent + 1, mappings, collect)
      js += ': '
      if (item.value) {
        js = visit(item.value, js, indent + 1, mappings, collect)
      } else {
        js += 'null'
      }
    }
    js += '\n'
    js += ' '.repeat((indent - 1) * 2)
    js += '}'
    return js
  }

  if (isScalar(node)) {
    const generated = JSON.stringify(node.value)
    const [start, end] = node.range
    mappings.push([js.length, generated.length, start, end - start, 1, 0])
    return js + generated
  }

  if (isAlias(node)) {
    return js + node.source
  }

  if (isSeq(node)) {
    js += '[\n'
    for (let index = 0; index < node.items.length; index += 1) {
      if (index !== 0) {
        js += ',\n'
      }
      const item = node.items[index]
      js += ' '.repeat(indent * 2)
      js = visit(item, js, indent + 1, mappings, collect)
    }
    js += '\n'
    js += ' '.repeat((indent - 1) * 2)
    js += ']'
    return js
  }

  throw new Error('Unknown node type', { cause: node })
}

definePlugin('remark-mdx-frontmatter', (options) => {
  const opts = isObject(options) ? options : {}
  const name = String(opts.name || 'frontmatter')

  /** @type {Literal | undefined} */
  let literal

  return {
    visit(node) {
      if (node.type === 'toml' || node.type === 'yaml') {
        literal = node
      }
    },

    finalize() {
      /** @type {SpanMapping[]} */
      const mappings = []
      let result =
        '/** Generated by [remark-mdx-frontmatter](https://github.com/remcohaszing/remark-mdx-frontmatter) */\n'
      result += `export const ${name} = `

      if (!literal) {
        return [`${result}undefined`, mappings]
      }

      if (literal.type === 'toml') {
        try {
          return [
            `${result}/** @type {const} */ (${JSON.stringify(parse(literal.value))})`,
            mappings
          ]
        } catch {
          return [`${result}/** @type {unknown} */ (undefined)`, mappings]
        }
      }

      if (literal.type === 'yaml') {
        const lineCounter = new LineCounter()
        const parser = new Parser(lineCounter.addNewLine)
        const composer = new Composer()
        const tokens = parser.parse(literal.value)
        const docs = composer.compose(tokens)
        const doc = nonNull(docs.next().value)

        if (!doc.contents) {
          return [`${result}/** @type {unknown} */ (undefined)`, mappings]
        }

        result += '(() => {\n'

        const expression = visit(doc.contents, '', 2, [], (identifier, code) => {
          result += `  const ${identifier} = /** @type {const} */ (${code})\n`
        })

        result += `  return /** @type {const} */ (${expression})\n`
        result += '})()'
        return [result, mappings]
      }

      return [`${result}/** @type {unknown} */ (undefined)`, mappings]
    }
  }
})
