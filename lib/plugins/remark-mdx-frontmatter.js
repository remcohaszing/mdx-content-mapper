/**
 * @import { ParsedNode } from 'yaml'
 * @import { Chunk } from '../util/chunk.js'
 */

import { parse } from 'toml'
import { Composer, isAlias, isMap, isScalar, isSeq, LineCounter, Parser } from 'yaml'

import { appendAliasRange, createChunk, mergeChunks } from '../util/chunk.js'
import { isObject, nonNull } from '../util/misc.js'
import { definePlugin } from '../util/plugin.js'

/**
 * Convert an unsafe name to a valid JavaScript identifier.
 *
 * @param {string} name
 * @returns {string}
 */
function toIdentifier(name) {
  return name.replaceAll(/[^\p{L}\d]/gu, '_').replace(/^\d/, '_')
}

/**
 * @param {ParsedNode} node
 * @param {Chunk} chunk
 * @param {number} indent
 * @param {string} yaml
 * @param {number} offset
 * @param {(name: string, chunk: Chunk) => undefined} collect
 * @param {boolean} [isAnchor]
 */
function visit(node, chunk, indent, yaml, offset, collect, isAnchor) {
  if (!isAnchor && node.anchor) {
    const anchor = `&${node.anchor}`
    const index = yaml.lastIndexOf(anchor, node.range[0])
    const identifier = toIdentifier(node.anchor)
    const anchorChunk = createChunk()
    visit(node, anchorChunk, 2, yaml, offset, collect, true)
    collect(identifier, anchorChunk)
    appendAliasRange(chunk, identifier, index + offset, anchor.length)
    return
  }

  if (isMap(node)) {
    chunk.text += '{\n'
    for (let index = 0; index < node.items.length; index += 1) {
      const item = node.items[index]
      if (index !== 0) {
        chunk.text += ',\n'
      }
      chunk.text += ' '.repeat(indent * 2)
      visit(item.key, chunk, indent + 1, yaml, offset, collect)
      chunk.text += ': '
      if (item.value) {
        visit(item.value, chunk, indent + 1, yaml, offset, collect)
      } else {
        chunk.text += 'null'
      }
    }
    chunk.text += '\n'
    chunk.text += ' '.repeat((indent - 1) * 2)
    chunk.text += '}'
    return
  }

  if (isScalar(node)) {
    const generated = JSON.stringify(node.value)
    const [start, end] = node.range
    appendAliasRange(chunk, generated, start + offset, end - start)
    return
  }

  if (isAlias(node)) {
    const identifier = toIdentifier(node.source)
    const [start, end] = node.range
    appendAliasRange(chunk, identifier, start + offset, end - start)
    return
  }

  if (isSeq(node)) {
    chunk.text += '[\n'
    for (let index = 0; index < node.items.length; index += 1) {
      if (index !== 0) {
        chunk.text += ',\n'
      }
      const item = node.items[index]
      chunk.text += ' '.repeat(indent * 2)
      visit(item, chunk, indent + 1, yaml, offset, collect)
    }
    chunk.text += '\n'
    chunk.text += ' '.repeat((indent - 1) * 2)
    chunk.text += ']'
  }
}

definePlugin('remark-mdx-frontmatter', (options) => {
  const opts = isObject(options) ? options : {}
  const name = String(opts.name || 'frontmatter')

  const prefix = `
/** Generated by [remark-mdx-frontmatter](https://github.com/remcohaszing/remark-mdx-frontmatter) */
export const ${name} = `

  return (content, esm) => {
    const frontmatter = createChunk()
    frontmatter.text += prefix

    let value = ''
    let offset = 0
    let entered = false
    let hasFrontmatter = false

    return {
      enter(token) {
        if ((entered && token.type === 'yamlFence') || token.type === 'tomlFence') {
          entered = false
          return
        }

        if (token.type === 'yamlValue' || token.type === 'tomlValue') {
          hasFrontmatter = true
          entered = true
        }

        if (entered) {
          offset ||= token.start.offset
          value += content.slice(token.start.offset, token.end.offset)
        }
      },

      exit(token) {
        if (token.type === 'toml') {
          entered = false
          frontmatter.text += '/** @type {const} */ ('
          frontmatter.text += JSON.stringify(parse(value))
          frontmatter.text += ')\n'
          return
        }

        if (token.type !== 'yaml') {
          return
        }

        entered = false
        const lineCounter = new LineCounter()
        const parser = new Parser(lineCounter.addNewLine)
        const composer = new Composer()
        const tokens = parser.parse(value)
        const docs = composer.compose(tokens)
        const doc = nonNull(docs.next().value)

        if (!doc.contents) {
          frontmatter.text += prefix
          frontmatter.text += '/** @type {unknown} */ (undefined)'
          return
        }

        const chunk = createChunk()
        frontmatter.text += '(() => {\n'
        visit(doc.contents, chunk, 2, value, offset, (identifier, anchorChunk) => {
          frontmatter.text += '  const '
          frontmatter.text += identifier
          frontmatter.text += ' = /** @type {const} */ ('
          mergeChunks(frontmatter, anchorChunk)
          frontmatter.text += ')\n'
        })
        frontmatter.text += '  return /** @type {const} */ ('
        mergeChunks(frontmatter, chunk)
        frontmatter.text += ')\n})()\n'
      },

      finalize() {
        if (!hasFrontmatter) {
          frontmatter.text += 'undefined\n'
        }

        mergeChunks(esm, frontmatter)
      }
    }
  }
})
