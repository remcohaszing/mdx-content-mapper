import { isObject } from '../util/misc.js'
import { definePlugin } from '../util/plugin.js'

definePlugin('recma-export-filepath', (options) => {
  const opts = isObject(options) ? options : {}
  const name = String(opts.name || 'filepath')

  return {
    finalize() {
      return [
        `/** Generated by [recma-export-filepath](https://github.com/remcohaszing/recma-export-filepath) */\nexport const ${
          name
        } = /** @type {string} */ ('')`,
        []
      ]
    }
  }
})
