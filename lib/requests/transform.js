/**
 * Render the content that should be prefixed to the embedded JavaScript file.
 *
 * @param {string} jsxImportSource
 *   The string to use for the JSX import source tag.
 */
const jsPrefix = (jsxImportSource) => `/* @jsxRuntime automatic */
/** @import { JSX } from '${jsxImportSource}/jsx-runtime' */

import { Fragment as _Fragment } from '${jsxImportSource}/jsx-runtime'
`

/**
 * @param {string} propsName
 */
const layoutJsDoc = (propsName) => `
/** @typedef {MDXContentProps & { children: JSX.Element }} MDXLayoutProps */

/**
 * There is one special component: [MDX layout](https://mdxjs.com/docs/using-mdx/#layout).
 * If it is defined, it’s used to wrap all content.
 * A layout can be defined from within MDX using a default export.
 *
 * @param {{readonly [K in keyof MDXLayoutProps]: MDXLayoutProps[K]}} ${propsName}
 *   The [props](https://mdxjs.com/docs/using-mdx/#props) that have been passed to the MDX component.
 *   In addition, the MDX layout receives the \`children\` prop, which contains the rendered MDX content.
 */`

/**
 * @param {boolean} isAsync
 *   Whether or not the `_createMdxContent` should be async
 * @param {Scope} [scope]
 * @param {boolean} [hasImportSource]
 */
const createMdxContentStart = (isAsync, scope, hasImportSource) => `
/**
 * @internal
 *   **Do not use.** This function is generated by MDX for internal use.
 *
 * @param {{readonly [K in keyof MDXContentProps]: MDXContentProps[K]}} props
 *   The [props](https://mdxjs.com/docs/using-mdx/#props) that have been passed to the MDX component.
 * @returns {${isAsync ? 'Promise<JSX.Element>' : 'JSX.Element'}}
 *   A JSX element which represents the MDX content.
 */
${isAsync ? 'async ' : ''}function _createMdxContent(props) {
  /**
   * @internal
   *   **Do not use.** This variable is generated by MDX for internal use.
   */
  const _components = {
    ...(/** @type {{[K in keyof JSX.IntrinsicElements]: K}} */ ({})),${hasImportSource ? '\n    ..._provideComponents(),' : ''}
    ...props.components,
    /** The [props](https://mdxjs.com/docs/using-mdx/#props) that have been passed to the MDX component. */
    props${
      scope?.defined.map((name) => `,\n    /** {@link ${name}} */\n    ${name}`).join('') ?? ''
    }
  }
  _components
  return <_Fragment>`

const createMdxContentEnd = `
  </_Fragment>
}
`

const mdxContentStart = `
/**
 * Render the MDX contents.
 *
 * @param {{readonly [K in keyof MDXContentProps]: MDXContentProps[K]}} props
 *   The [props](https://mdxjs.com/docs/using-mdx/#props) that have been passed to the MDX component.
 * @returns {JSX.Element}
 *   A JSX element which represents the MDX content.
 */
export default function MDXContent(props) {
  return `

/**
 * @param {string} [propsType]
 */
const mdxContentEnd = (propsType = 'Props') => `
}

// @ts-ignore
/** @typedef {(void extends ${propsType} ? {} : ${propsType}) & {components?: {}}} MDXContentProps */
`

/**
 * A fallback to use if generating mapped content fails.
 *
 * @param {string} jsxImportSource
 *   The string to use for the JSX import source tag.
 */
const fallback = (jsxImportSource) =>
  jsPrefix(jsxImportSource) +
  createMdxContentStart(false) +
  createMdxContentEnd +
  mdxContentStart +
  mdxContentEnd()

/**
 * @param {ExportDefaultDeclaration} node
 * @returns {string | undefined}
 */
function getPropsName(node) {
  const { declaration } = node
  const { type } = declaration

  if (
    type !== 'ArrowFunctionExpression' &&
    type !== 'FunctionDeclaration' &&
    type !== 'FunctionExpression'
  ) {
    return
  }

  if (declaration.params.length === 1) {
    const parameter = declaration.params[0]
    if (parameter.type === 'Identifier') {
      return parameter.name
    }
  }

  return 'props'
}

/**
 * @param {Event[]} events
 * @param {number} index
 * @param {TokenType} tokenType
 * @returns {Token}
 */
function findToken(events, index, tokenType) {
  /** @type {Token | undefined} */
  let match
  for (let i = index; i < events.length; i += 1) {
    const token = events[i][1]
    if (token.type === tokenType) {
      match = token
      break
    }
  }
  return nonNull(match)
}

/**
 * @param {Event[]} events
 * @param {number} index
 * @param {TokenType} tokenType
 * @returns {Token}
 */
function findTokenLast(events, index, tokenType) {
  /** @type {Token | undefined} */
  let match
  for (let i = index; i >= 0; i -= 1) {
    const token = events[i][1]
    if (token.type === tokenType) {
      match = token
      break
    }
  }
  return nonNull(match)
}

/**
 * @param {Event[]} events
 * @param {number} index
 * @param {Chunk} chunk
 * @param {string} content
 */
function extendEsmWhitespace(events, index, chunk, content) {
  /** @type {Token | undefined} */
  let mappingToken

  for (let i = index; i < events.length; i += 1) {
    const [event, token] = events[i]
    if (token.type === 'lineEnding') {
      if (event === 'enter') {
        appendVerbatim(chunk, content, token)
      }
    } else {
      mappingToken = token
      break
    }
  }

  mappingToken ??= events.at(-1)?.[1]

  if (!mappingToken) {
    return
  }

  chunk.text += '\n'
  chunk.mappings.push([
    chunk.text.length,
    1,
    mappingToken.start.offset,
    1,
    /** @satisfies {SpanMapKind.Alias} */ (2),
    /** @satisfies {SpanMapFeature.None} */ (0)
  ])
  chunk.text += ';\n'
}

/**
 * @param {TransformParams} params
 * @param {Project} project
 * @returns {TransformResult}
 */
function transformActual({ content, fileName }, project) {
  const {
    checkCodeBlocks,
    checkMdx,
    configFileName,
    jsxImportSource,
    mdExtensions,
    micromarkExtensions,
    plugins,
    preset,
    providerImportSource
  } = project
  const resolvedProviderImportSource = resolveProviderImportSource(
    fileName,
    configFileName,
    providerImportSource
  )

  const extensions = hasExtension(fileName, mdExtensions)
    ? []
    : [
        mdxExpression({ acorn, addResult: true }),
        mdxJsx({ acorn, addResult: true }),
        mdxMd(),
        mdxjsEsm({ acorn, addResult: true })
      ]
  const visitors = createVisitors()
  const programScope = visitors.scopes[0]
  const esm = createChunk()
  const jsx = createChunk()
  const jsxVariables = createChunk()
  const pluginObjects = plugins.map((plugin) => plugin(content, esm))

  /** @type {MappedOutput[]} */
  const supplemental = []

  let hasAwait = false

  /** @type {Node | undefined} */
  let layoutNode

  /** @type {string | undefined} */
  let propsType
  if (configFileName) {
    switch (preset) {
      case '@react-router/fs-routes': {
        const routerFields = getReactRouterPropsType(configFileName, fileName)
        if (routerFields) {
          propsType = routerFields.type
          esm.text += routerFields.import
        }
        break
      }
      case 'next':
        propsType = getNextPropsType(configFileName, fileName)
        break
    }
  }

  if (checkMdx) {
    esm.text += '// @ts-check\n'
  }

  esm.text += jsPrefix(jsxImportSource)

  if (resolvedProviderImportSource) {
    esm.text += `import { useMDXComponents as _provideComponents } from ${JSON.stringify(resolvedProviderImportSource)}\n`
  }

  const events = postprocess(
    parse({ extensions: extensions.concat(micromarkExtensions) })
      .document()
      .write(preprocess()(content, undefined, true))
  )

  let isJsx = false
  let depth = 0

  /** @type {Chunk & MappedOutput | undefined} */
  let codeBlock
  let isCodeFenced = false

  /** @type {Program[]} */
  const expressionPrograms = []

  /** @type {Map<Node, Scope | undefined>} */
  const localScopes = new Map()

  /** @type {Map<Node, Node | null>} */
  const parents = new Map()

  /** @type {JSXIdentifier[]} */
  const jsxIdentifiers = []

  /** @type {number[]} */
  const injectionPoints = []

  /** @type {Token[]} */
  const mdxJsxPrimaryTagNames = []

  /** @type {[tagName: string, count: number][]} */
  const listStack = []

  for (let index = 0; index < events.length; index += 1) {
    const [event, token] = events[index]
    if (event === 'enter') {
      depth += 1
    } else {
      depth -= 1
    }

    for (const plugin of pluginObjects) {
      plugin[event]?.(token)
    }

    switch (/** @type {const} */ (`${event}:${token.type}`)) {
      case 'enter:mdxJsxFlowTagAttributeValueExpression':
      case 'enter:mdxJsxTextTagAttributeValueExpression':
        isJsx = true
        expressionPrograms.push(nonNull(token.estree))
        break
      case 'enter:mdxFlowExpression':
      case 'enter:mdxTextExpression': {
        const program = nonNull(token.estree)
        jsx.text += jsxIndent
        isJsx = true
        if (depth === 1 && program.body.length === 0) {
          appendVerbatimRange(esm, content, program.start, program.end - program.start)
        } else {
          expressionPrograms.push(program)
        }
        break
      }
      case 'enter:mdxJsxFlowTag':
      case 'enter:mdxJsxTextTag':
        jsx.text += jsxIndent
        isJsx = true
        break
      case 'exit:mdxFlowExpression':
      case 'exit:mdxJsxFlowTag':
      case 'exit:mdxJsxTextTag':
      case 'exit:mdxTextExpression':
        isJsx = false
        break
      case 'enter:mdxjsEsm': {
        const program = nonNull(token.estree)
        walk(program, {
          enter(node) {
            if (node.type === 'Program') {
              return
            }
            visitors.enter(node)
            if (isFunctionNode(node)) {
              this.skip()
              visitors.exit(node)
            }
          },
          leave(node) {
            if (node.type === 'Program') {
              return
            }

            visitors.exit(node)
          }
        })

        bodyLoop: for (let childIndex = 0; childIndex < program.body.length; childIndex += 1) {
          const child = program.body[childIndex]
          const next = program.body[childIndex + 1]
          let { end } = child
          if (next) {
            end = next.start
          }

          if (child.type === 'ExportDefaultDeclaration') {
            const propsName = getPropsName(child)
            layoutNode = child
            if (propsName) {
              esm.text += layoutJsDoc(propsName)
            }

            esm.text += '\nconst MDXLayout = '
            appendVerbatimRange(
              esm,
              content,
              child.declaration.start,
              end - child.declaration.start
            )
            continue
          }

          if (child.type === 'ExportNamedDeclaration' && child.source) {
            const { specifiers } = child
            for (let specifierIndex = 0; specifierIndex < specifiers.length; specifierIndex += 1) {
              const specifier = specifiers[specifierIndex]
              if (
                specifier.local.type === 'Identifier'
                  ? specifier.local.name === 'default'
                  : specifier.local.value === 'default'
              ) {
                layoutNode = specifier
                appendVerbatimRange(
                  esm,
                  content,
                  token.start.offset,
                  specifier.start - token.start.offset
                )
                const nextPosition =
                  specifierIndex === specifiers.length - 1
                    ? specifier.end
                    : content.indexOf(',', specifier.end) + 1
                appendVerbatimRange(esm, content, nextPosition, token.end.offset - nextPosition)
                esm.text += '\nimport {'
                esm.text +=
                  specifier.exported.type === 'Identifier'
                    ? specifier.exported.name
                    : JSON.stringify(specifier.exported.value)
                esm.text += ' as MDXLayout} from '
                const sourceLength = child.source.end - child.source.start
                esm.mappings.unshift([
                  esm.text.length,
                  sourceLength,
                  child.source.start,
                  sourceLength,
                  0,
                  0
                ])
                esm.text += child.source.raw
                continue bodyLoop
              }
            }
          }

          appendVerbatimRange(esm, content, child.start, end - child.start)
        }
        break
      }
      case 'exit:mdxjsEsm':
        extendEsmWhitespace(events, index + 1, esm, content)
        break

      case 'enter:lineEnding':
        if (isJsx) {
          appendVerbatim(jsx, content, token)
        }
        break

      case 'enter:esWhitespace':
      case 'enter:mdxFlowExpressionChunk':
      case 'enter:mdxFlowExpressionMarker':
      case 'enter:mdxJsxFlowTagAttributeInitializerMarker':
      case 'enter:mdxJsxFlowTagAttributeNamePrimary':
      case 'enter:mdxJsxFlowTagAttributeValueExpressionMarker':
      case 'enter:mdxJsxFlowTagAttributeValueExpressionValue':
      case 'enter:mdxJsxFlowTagAttributeValueLiteralMarker':
      case 'enter:mdxJsxFlowTagAttributeValueLiteralValue':
      case 'enter:mdxJsxFlowTagClosingMarker':
      case 'enter:mdxJsxFlowTagMarker':
      case 'enter:mdxJsxFlowTagNameMember':
      case 'enter:mdxJsxFlowTagNameMemberMarker':
      case 'enter:mdxJsxFlowTagSelfClosingMarker':
      case 'enter:mdxJsxTextTagAttributeInitializerMarker':
      case 'enter:mdxJsxTextTagAttributeNamePrimary':
      case 'enter:mdxJsxTextTagAttributeValueExpressionMarker':
      case 'enter:mdxJsxTextTagAttributeValueExpressionValue':
      case 'enter:mdxJsxTextTagAttributeValueLiteralMarker':
      case 'enter:mdxJsxTextTagAttributeValueLiteralValue':
      case 'enter:mdxJsxTextTagClosingMarker':
      case 'enter:mdxJsxTextTagMarker':
      case 'enter:mdxJsxTextTagNameMember':
      case 'enter:mdxJsxTextTagNameMemberMarker':
      case 'enter:mdxJsxTextTagSelfClosingMarker':
      case 'enter:mdxTextExpressionChunk':
      case 'enter:mdxTextExpressionMarker':
        appendVerbatim(jsx, content, token)
        break

      case 'enter:mdxJsxFlowTagNamePrimary':
      case 'enter:mdxJsxTextTagNamePrimary':
        appendVerbatim(jsx, content, token)
        mdxJsxPrimaryTagNames.push(token)
        break

      case 'enter:data':
        if (!isCodeFenced && events[index - 1][1].type !== 'data') {
          jsx.text += jsxIndent
          jsx.text += "{''}"
        }
        break

      case 'enter:paragraph':
        // TODO add namespace
        jsx.text += jsxIndent
        jsx.text += '<p>'
        break
      case 'exit:paragraph':
        // TODO add namespace
        jsx.text += jsxIndent
        jsx.text += '</p>'
        break

      case 'enter:atxHeadingSequence':
        appendJsxOpen(jsx, token, `h${token.end.offset - token.start.offset}`)
        break
      case 'exit:atxHeading': {
        const sequence = findTokenLast(events, index, 'atxHeadingSequence')
        appendJsxCloseUnmapped(jsx, `h${sequence.end.offset - sequence.start.offset}`)
        break
      }

      case 'enter:setextHeading': {
        const sequence = findToken(events, index, 'setextHeadingLineSequence')
        appendJsxOpen(jsx, sequence, content.charAt(sequence.start.offset) === '=' ? 'h1' : 'h2')
        break
      }
      case 'enter:setextHeadingLineSequence':
        appendJsxCloseUnmapped(jsx, content.charAt(token.start.offset) === '=' ? 'h1' : 'h2')
        break

      case 'enter:codeFenced': {
        const sequence = findToken(events, index, 'codeFencedFenceSequence')
        appendJsxOpen(jsx, sequence, 'pre')
        appendJsxOpen(jsx, sequence, 'code')
        isCodeFenced = true
        break
      }
      case 'exit:codeFenced': {
        // TODO handle unclosed code fences.
        const sequence = findTokenLast(events, index, 'codeFencedFenceSequence')
        appendJsxClose(jsx, sequence, 'code')
        appendJsxClose(jsx, sequence, 'pre')
        if (codeBlock) {
          supplemental.push(codeBlock)
        }
        isCodeFenced = false
        codeBlock = undefined
        break
      }

      case 'enter:codeFencedFenceInfo':
        if (checkCodeBlocks) {
          const extension = codeExtensions.get(content.slice(token.start.offset, token.end.offset))
          if (extension) {
            codeBlock = { ...createChunk(), extension }
          }
        }
        break

      case 'enter:codeFlowValue':
        if (codeBlock) {
          appendVerbatim(codeBlock, content, token)
          const lineEnding = events[index + 2][1]
          if (lineEnding.type === 'lineEnding') {
            appendVerbatim(codeBlock, content, lineEnding)
          }
        }
        break

      case 'enter:blockQuote': {
        const sequence = findToken(events, index, 'blockQuotePrefix')
        appendJsxOpen(jsx, sequence, 'blockquote')
        break
      }
      case 'exit:blockQuote':
        appendJsxCloseUnmapped(jsx, 'blockquote')
        break

      case 'enter:hardBreakEscape':
      case 'enter:hardBreakTrailing':
        appendJsxSelfClosing(jsx, token, 'br')
        break

      case 'enter:thematicBreak':
        appendJsxSelfClosing(jsx, token, 'hr')
        break

      case 'enter:strong':
        appendJsxOpen(jsx, events[index + 1][1], 'strong')
        break
      case 'exit:strong':
        appendJsxClose(jsx, events[index - 1][1], 'strong')
        break

      case 'enter:emphasis':
        appendJsxOpen(jsx, events[index + 1][1], 'em')
        break
      case 'exit:emphasis':
        appendJsxClose(jsx, events[index - 1][1], 'em')
        break

      case 'enter:codeText':
        appendJsxOpen(jsx, events[index + 1][1], 'code')
        break
      case 'exit:codeText':
        appendJsxClose(jsx, events[index - 1][1], 'code')
        break

      case 'enter:strikethrough':
        appendJsxOpen(jsx, events[index + 1][1], 'del')
        break
      case 'exit:strikethrough':
        appendJsxClose(jsx, events[index - 1][1], 'del')
        break

      case 'enter:listUnordered':
        listStack.push(['ul', 1])
        break
      case 'exit:listUnordered':
        listStack.pop()
        appendJsxCloseUnmapped(jsx, 'li')
        appendJsxCloseUnmapped(jsx, 'ul')
        break

      case 'enter:listOrdered':
        listStack.push(['ol', 1])
        break
      case 'exit:listOrdered':
        listStack.pop()
        appendJsxCloseUnmapped(jsx, 'li')
        appendJsxCloseUnmapped(jsx, 'ol')
        break
      case 'enter:listItemPrefix': {
        const start = events[index + 1][1].start.offset
        const end = findToken(events, index, 'listItemMarker').end.offset
        const listState = nonNull(listStack.at(-1))
        if (listState[1] !== 1) {
          appendJsxCloseUnmapped(jsx, 'li')
          appendJsxCloseUnmapped(jsx, listState[0])
        }
        appendJsxRange(jsx, listState[0], start, end - start)
        appendJsxRange(jsx, 'li', start, end - start)
        listState[1] += 1
        break
      }

      case 'enter:literalAutolink':
        appendJsxOpen(jsx, token, 'a')
        jsx.text += jsxIndent
        jsx.text += "{''}"
        appendJsxClose(jsx, token, 'a')
        break

      case 'enter:taskListCheck':
        appendJsxSelfClosing(jsx, token, 'input')
    }
  }

  for (const program of expressionPrograms) {
    walk(program, {
      // eslint-disable-next-line no-loop-func
      enter(node, parent) {
        if (node.type === 'Program') {
          return
        }

        visitors.enter(node)
        localScopes.set(node, visitors.scopes.at(-1))
        parents.set(node, parent)

        if (node.type === 'JSXIdentifier') {
          jsxIdentifiers.push(node)
        }

        hasAwait ||= isAsyncMdx(node, parents)
      },

      leave(node) {
        if (node.type === 'Program') {
          return
        }

        visitors.exit(node)
      }
    })
  }

  for (const plugin of pluginObjects) {
    plugin.finalize?.()
  }

  for (const node of jsxIdentifiers) {
    if (isInjectableEstree(node, localScopes, parents)) {
      jsxVariables.text += '// @ts-ignore\n'
      appendVerbatimRange(jsxVariables, content, node.start, node.end - node.start)
      jsxVariables.text += '\n'
      injectionPoints.push(node.start)
    }
  }

  for (const token of mdxJsxPrimaryTagNames) {
    const name = content.slice(token.start.offset, token.end.offset)
    if (isInjectableComponent(name, programScope)) {
      jsxVariables.text += '// @ts-ignore\n'
      appendVerbatim(jsxVariables, content, token)
      jsxVariables.text += '\n'
      injectionPoints.push(token.start.offset)
    }
  }

  injectComponentsNamespace(jsx, injectionPoints)

  esm.text += createMdxContentStart(hasAwait, programScope, Boolean(resolvedProviderImportSource))

  mergeChunks(esm, jsx)

  esm.text += createMdxContentEnd
  esm.text += mdxContentStart
  esm.text += '<'
  if (layoutNode) {
    appendAliasRange(esm, 'MDXLayout', layoutNode.start, layoutNode.end - layoutNode.start)
    esm.text += ' {...props}'
  } else {
    esm.text += '_Fragment'
  }
  esm.text += '>\n'
  esm.text += '    <_createMdxContent {...props} />\n'
  esm.text += `  </${layoutNode ? 'MDXLayout' : '_Fragment'}>`
  esm.text += mdxContentEnd(propsType)

  mergeChunks(esm, jsxVariables)

  return {
    ...esm,
    extension: '.jsx',
    supplemental
  }
}

/**
 * Transform MDX content into mapped TypeScript content.
 *
 * @param {TransformParams} params
 *   The transform parameters as sent by TypeScript.
 * @returns {TransformResult}
 *   The transform result that TypeScript expects.
 */
export function transform(params) {
  const project = nonNull(projects.get(params.projectHandle))

  try {
    return transformActual(params, project)
  } catch (error) {
    return {
      diagnostics: [toDiagnostic(error)],
      mappings: [],
      extension: '.jsx',
      text: fallback(project.jsxImportSource)
    }
  }
}
